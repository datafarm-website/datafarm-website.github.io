/* DATAFARM project page: "Human teleoperation or DATAFARM?" game. Rounds come from game-rounds.js. */
(function () {
  'use strict';

  var ROUNDS = window.GAME_ROUNDS;
  var root = document.getElementById('game');
  if (!root || !ROUNDS || !ROUNDS.length) return;
  root.hidden = false;

  var BASE = 'static/videos/game/';
  var reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  var clips = Array.prototype.slice.call(root.querySelectorAll('.game-clip'));
  var vids = clips.map(function (c) { return c.querySelector('video'); });
  var picks = clips.map(function (c) { return c.querySelector('.game-pick'); });
  var reveals = clips.map(function (c) { return c.querySelector('.game-reveal'); });
  var $ = function (id) { return document.getElementById(id); };
  var roundEl = $('g-round'), scoreEl = $('g-score'), taskEl = $('g-task');
  var dotsEl = $('g-dots'), resultEl = $('g-result'), nextBtn = $('g-next');

  var order, i, score, tampSide, answered, done, visible = false;
  var view = 'ext', rate = 2;

  function shuffle(a) {
    a = a.slice();
    for (var k = a.length - 1; k > 0; k--) {
      var j = Math.floor(Math.random() * (k + 1)), t = a[k];
      a[k] = a[j]; a[j] = t;
    }
    return a;
  }

  function clipId(round, side) { return side === tampSide ? round.tamp : round.teleop; }
  function url(id, v) { return BASE + id + '-' + v + '.mp4'; }

  function play() {
    if (reduceMotion || !visible) return;
    vids.forEach(function (vd) {
      var p = vd.play();
      if (p && p.catch) p.catch(function () { vd.controls = true; });
    });
  }

  // Load both clips; keep each clip's position when only the camera changes.
  function load(keepTime) {
    var r = order[i];
    vids.forEach(function (vd, side) {
      var t = keepTime ? vd.currentTime : 0;
      vd.poster = BASE + clipId(r, side) + '.jpg';
      vd.src = url(clipId(r, side), view);
      vd.defaultPlaybackRate = vd.playbackRate = rate;
      if (t) vd.addEventListener('loadedmetadata', function once() {
        vd.removeEventListener('loadedmetadata', once);
        vd.currentTime = Math.min(t, vd.duration || t);
      });
    });
    play();
  }

  function prefetch(r) {
    if (!r) return;
    [r.tamp, r.teleop].forEach(function (id) {
      var l = document.createElement('link');
      l.rel = 'prefetch'; l.href = url(id, view); l.as = 'video';
      document.head.appendChild(l);
    });
  }

  function drawDots() {
    dotsEl.innerHTML = '';
    order.forEach(function (r, k) {
      var d = document.createElement('i');
      if (r.result) d.className = r.result;
      else if (k === i) d.className = 'cur';
      dotsEl.appendChild(d);
    });
  }

  function status() {
    roundEl.textContent = 'Round ' + (i + 1) + ' of ' + order.length;
    scoreEl.textContent = score + ' correct';
  }

  function startRound() {
    var r = order[i];
    tampSide = Math.random() < 0.5 ? 0 : 1;
    answered = false;
    taskEl.textContent = 'Task: ' + r.task;
    clips.forEach(function (c) { c.classList.remove('is-tamp', 'is-teleop', 'picked', 'right', 'wrong'); });
    picks.forEach(function (b) { b.disabled = false; });
    resultEl.innerHTML = '';
    nextBtn.hidden = true;
    status();
    drawDots();
    load(false);
  }

  function newGame() {
    order = shuffle(ROUNDS).map(function (r) { return { task: r.task, tamp: r.tamp, teleop: r.teleop }; });
    i = 0; score = 0; done = false;
    startRound();
  }

  function pick(side) {
    if (answered) return;
    answered = true;
    var right = side === tampSide, letter = 'AB';
    if (right) score++;
    order[i].result = right ? 'right' : 'wrong';
    clips.forEach(function (c, s) {
      c.classList.add(s === tampSide ? 'is-tamp' : 'is-teleop');
      reveals[s].textContent = s === tampSide ? 'DATAFARM (planner)' : 'Human teleoperation';
    });
    clips[side].classList.add('picked', right ? 'right' : 'wrong');
    picks.forEach(function (b) { b.disabled = true; });
    resultEl.innerHTML = right
      ? '<b>Correct.</b> ' + letter[tampSide] + ' was generated by DATAFARM.'
      : '<b>Not this time.</b> ' + letter[tampSide] + ' was DATAFARM; ' + letter[side] + ' was a person teleoperating.';
    status();
    drawDots();

    var last = i === order.length - 1;
    nextBtn.textContent = last ? 'See results' : 'Next round →';
    nextBtn.hidden = false;
    if (!last) prefetch(order[i + 1]);
  }

  function finish() {
    var n = order.length;
    resultEl.innerHTML = '<b>You spotted DATAFARM in ' + score + ' of ' + n + ' rounds.</b> ' +
      (score <= Math.ceil(n * 0.6)
        ? 'Guessing gets ' + (n / 2) + ' on average: the planner&rsquo;s motion is hard to tell apart from a person&rsquo;s.'
        : 'Sharp eye. The tells that remain: the planner lifts objects a little higher and moves with a steady ripple of small speed pulses rather than a person&rsquo;s few large bursts.');
    nextBtn.textContent = 'Play again';
    roundEl.textContent = 'Game over';
    done = true;
  }

  picks.forEach(function (b, side) { b.addEventListener('click', function () { pick(side); }); });

  nextBtn.addEventListener('click', function () {
    if (done) return newGame();
    if (i === order.length - 1) return finish();
    i++;
    startRound();
  });

  function segment(id, attr, set) {
    var seg = $(id);
    seg.querySelectorAll('button').forEach(function (b) {
      b.addEventListener('click', function () {
        seg.querySelectorAll('button').forEach(function (o) { o.classList.toggle('active', o === b); });
        set(b.getAttribute(attr));
      });
    });
  }
  segment('g-view', 'data-view', function (v) { if (v !== view) { view = v; load(true); } });
  segment('g-speed', 'data-rate', function (x) {
    rate = +x;
    vids.forEach(function (vd) { vd.defaultPlaybackRate = vd.playbackRate = rate; });
  });

  $('g-restart').addEventListener('click', function () {
    vids.forEach(function (vd) { vd.currentTime = 0; });
    if (reduceMotion) vids.forEach(function (vd) { vd.play(); });
    else play();
  });

  if (reduceMotion) vids.forEach(function (vd) { vd.controls = true; vd.preload = 'metadata'; });

  // Play only while the game is on screen.
  if ('IntersectionObserver' in window) {
    new IntersectionObserver(function (entries) {
      visible = entries[0].isIntersecting;
      if (visible) play();
      else vids.forEach(function (vd) { vd.pause(); });
    }, { rootMargin: '100px 0px' }).observe(root);
  } else {
    visible = true;
  }

  newGame();
})();
